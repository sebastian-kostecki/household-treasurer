export function resolveCategoryIcon(name: string): LucideIcon {
    return categoryIconMap[name] ?? Tag;
}

export type CategoryAppearanceFields = {
    icon: string;
    color: string;
};

export type CategoryPickerGroup = { id: number; name: string };

export type CategoryPickerOption = CategoryAppearanceFields & {
    id: number;
    name: string;
    group?: CategoryPickerGroup | null;
};

export type CategoryAppearanceOptions = {
    icons: string[];
    colors: string[];
};

export function categoryTileStyle(color: string): {
    backgroundColor: string;
    color: string;
} {
    return {
        backgroundColor: `${color}26`,
        color,
    };
}
